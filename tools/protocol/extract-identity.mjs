// tools/protocol/extract-identity.mjs
//
// 把 Avalanche CLI 建链产出的 sidecar.json 重塑成 blockchain/chain-identity/karmachain.identity.json。
//
// 这是「第二类事实」的提取器（研究 R-04）：SubnetID / BlockchainID 是 P 链交易的产物，
// 无法由 protocol.json 纯函数推导，只能一次性建链后提取、固化、由漂移测试与启动期校验保护。
//
// 提取的同时做交叉校验 —— 制品必须与 protocol.json 声明的版本、网络、验证者数量一致，
// 否则说明这份 sidecar 来自另一次建链或另一套参数，宁可失败也不能写出一份自相矛盾的制品。
//
// 用法：node tools/protocol/extract-identity.mjs <sidecar.json> [--network "Local Network"] [--out <path>]
//       不带 --out 时打印到标准输出。

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import Ajv from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import { loadProtocol, readJson, REPO_ROOT } from './load.mjs';

export const DEFAULT_NETWORK = 'Local Network';
export const OUTPUT_PATH = resolve(REPO_ROOT, 'blockchain', 'chain-identity', 'karmachain.identity.json');
const SCHEMA_PATH = resolve(REPO_ROOT, 'blockchain', 'chain-identity.schema.json');

/**
 * @param {object} sidecar  CLI 的 subnets/<name>/sidecar.json
 * @param {object} p        已校验的 protocol.json
 * @param {{network?: string, createdAt?: string}} [opts]
 */
export function extractIdentity(sidecar, p, opts = {}) {
  const network = opts.network ?? DEFAULT_NETWORK;
  const net = sidecar?.Networks?.[network];
  if (!net) {
    const have = Object.keys(sidecar?.Networks ?? {}).join(', ') || '(none)';
    throw new Error(`sidecar has no Networks["${network}"]; available: ${have}`);
  }

  const problems = [];
  const want = (label, got, expected) => {
    if (got !== expected) problems.push(`${label}: sidecar ${JSON.stringify(got)}, protocol.json ${JSON.stringify(expected)}`);
  };

  // 交叉校验：制品必须与协议参数同源
  want('VM version', sidecar.VMVersion, p.avalanche.subnetEvmVersion);
  want('RPCChainVM protocol', net.RPCVersion ?? sidecar.RPCVersion, p.avalanche.rpcChainVmProtocol);
  want('blockchain name', sidecar.Name, p.chain.blockchainName);
  // 只比符号：CLI 会把 TokenName 自造成 "<symbol> Token"，与 protocol.json 的 nativeToken.name 无关
  want('token symbol', sidecar.TokenSymbol, p.nativeToken.symbol);

  const validators = net.BootstrapValidators ?? [];
  if (validators.length !== p.validators.count) {
    problems.push(`bootstrap validators: sidecar has ${validators.length}, validators.count is ${p.validators.count}`);
  }
  const weights = new Set(validators.map((v) => v.Weight));
  if (weights.size > 1) {
    problems.push(`bootstrap validators must be equal-weight (fault tolerance derivation assumes it); got ${[...weights].join(', ')}`);
  }

  if (problems.length) {
    throw new Error(`sidecar does not match protocol.json:\n  - ${problems.join('\n  - ')}`);
  }

  return {
    $comment: 'GENERATED by tools/protocol/extract-identity.mjs from a one-time chain bootstrap — DO NOT EDIT. '
      + 'Second-class fact: not derivable from protocol.json (BlockchainID depends on the CreateChainTx id).',
    subnetId: net.SubnetID,
    blockchainId: net.BlockchainID,
    chainAlias: p.chain.blockchainName,
    vm: sidecar.VM,
    vmVersion: sidecar.VMVersion,
    rpcVersion: net.RPCVersion ?? sidecar.RPCVersion,
    networkId: p.avalanche.networkId,
    bootstrapValidators: validators.map((v) => ({
      nodeId: v.NodeID,
      weight: v.Weight,
      balance: v.Balance,
      blsPublicKey: v.BLSPublicKey,
      blsProofOfPossession: v.BLSProofOfPossession,
      changeOwnerAddr: v.ChangeOwnerAddr,
      validationId: v.ValidationID,
    })),
    createdAt: opts.createdAt ?? new Date().toISOString().replace(/\.\d{3}Z$/, 'Z'),
  };
}

/** 用 chain-identity.schema.json 校验制品。返回错误信息数组（空 = 合法）。 */
export function validateIdentity(identity, schema = readJson(SCHEMA_PATH)) {
  // strict 模式下未知 format 会抛异常，createdAt 用了 date-time —— 与 load.mjs 一致地注册格式
  const ajv = addFormats(new Ajv({ strict: true, allErrors: true }));
  const validate = ajv.compile(schema);
  if (validate(identity)) return [];
  return validate.errors.map((e) => `${e.instancePath || '/'} ${e.message}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const args = process.argv.slice(2);
  const positional = args.filter((a) => !a.startsWith('--') && args[args.indexOf(a) - 1] !== '--network' && args[args.indexOf(a) - 1] !== '--out');
  const sidecarPath = positional[0];
  if (!sidecarPath) {
    console.error('usage: node tools/protocol/extract-identity.mjs <sidecar.json> [--network "Local Network"] [--out <path>]');
    process.exit(10);
  }
  const ni = args.indexOf('--network');
  const oi = args.indexOf('--out');

  try {
    const identity = extractIdentity(
      readJson(resolve(sidecarPath)),
      loadProtocol(),
      { network: ni !== -1 ? args[ni + 1] : undefined },
    );
    const errors = validateIdentity(identity);
    if (errors.length) {
      console.error(`extracted identity fails chain-identity.schema.json:\n  - ${errors.join('\n  - ')}`);
      process.exit(1);
    }
    const text = `${JSON.stringify(identity, null, 2)}\n`;
    if (oi !== -1) {
      const out = resolve(args[oi + 1] ?? OUTPUT_PATH);
      mkdirSync(dirname(out), { recursive: true });
      writeFileSync(out, text);
      console.log(`wrote ${out}`);
      console.log(`  subnet ${identity.subnetId}`);
      console.log(`  blockchain ${identity.blockchainId}  alias ${identity.chainAlias}`);
      console.log(`  ${identity.bootstrapValidators.length} bootstrap validators, weight ${identity.bootstrapValidators[0]?.weight}`);
    } else {
      process.stdout.write(text);
    }
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
}
