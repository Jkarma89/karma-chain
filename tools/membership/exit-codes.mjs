// tools/membership/exit-codes.mjs —— 成员管理三个工具**共用**的退出码（功能 005 / FR-017）。
//
// ## 为什么要有这个文件
//
// 加入与退出各自实现时，各挑各的号，结果同一件事在两个工具里是两个答案：
//
//   add-validator     前置检查未过 = 13   某步失败 = 14   人工中止 = 20
//   remove-validator  前置检查未过 = 11   某步失败 = 12   人工中止 = 3
//
// 而 11 / 12 / 13 / 20 在本仓库**早就有含义**（001 契约的四类 + 002 新增的 13）：
//
//   10 前置依赖缺失   11 端口冲突   12 数据与声明不一致   13 拓扑违反容错约束   20 启动失败
//
// 于是「退出码 12」在一处是"节点数据不属于这条链"、在另一处是"P 链交易失败了"。
// 靠退出码分流的调用方（CI、脚本、运维手册）会把两件毫不相干的事当成同一件。
//
// 号段挪到 **3x**，三个工具从这里取，谁都不再自己定义。
// 守卫见 `tests/unit/membership-exit-codes.test.mjs`：
// 既禁止与保留号段相撞，也禁止两个工具各自声明。
export const EXIT_OK = 0;

/** 前置依赖缺失（docker / 镜像 / 声明不可读）。与 001 同义，入口脚本用。 */
export const EXIT_DEPS = 10;

/** 前置检查未通过 —— **一步都没动链**。 */
export const EXIT_PRECHECK = 30;

/** 某一步失败 —— 输出会报出停在哪一步，可重试。 */
export const EXIT_STEP_FAILED = 31;

/** 人工中止（回答"否"或按了 Ctrl-C 之前的确认点）。链未改动。 */
export const EXIT_ABORTED = 32;

/** 只读报告发现漂移：声明与链上不一致，或合约侧与 P 链侧分歧。 */
export const EXIT_DRIFT = 33;

/**
 * 本仓库在 005 之前就占用的退出码，**成员工具不得复用**。
 * 出处：001 `contracts/cli-interface.md`（10/11/12/20）与 002 的新增码 13。
 */
export const RESERVED_BEFORE_005 = Object.freeze({
  10: '前置依赖缺失',
  11: '端口冲突',
  12: '数据与声明不一致（节点出生证明拒绝旧数据）',
  13: '拓扑违反容错约束',
  20: '启动失败',
});
